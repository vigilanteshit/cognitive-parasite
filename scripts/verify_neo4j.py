"""Verify a disposable Neo4j service with synthetic, uniquely scoped records."""

import asyncio
import json
import os
from pathlib import Path
from uuid import uuid4

from data_parasite.config import Settings
from data_parasite.memory import EmbeddingMismatch, MemoryRecord, Neo4jMemoryStore
from data_parasite.providers import ModelRouter


async def verify():
    uri = os.environ["PARASITE_NEO4J_TEST_URI"]
    password = os.environ["PARASITE_NEO4J_TEST_PASSWORD"]
    provider = ModelRouter(Settings(_env_file=None, models_file=Path("__no_profiles__")))
    store = Neo4jMemoryStore(
        uri, "neo4j", password, embedding_model="demo:hash-v1", embedding_dimensions=64
    )
    scope = "synthetic-verification-" + str(uuid4())
    try:
        # Container startup can take several seconds; never use thesis credentials.
        for attempt in range(30):
            try:
                await store.driver.verify_connectivity()
                break
            except Exception:
                if attempt == 29:
                    raise RuntimeError("Disposable Neo4j service did not become ready") from None
                await asyncio.sleep(2)
        await store.initialize()
        async with store.driver.session(database=store.database) as session:
            result = await session.run("CALL db.awaitIndexes(120)")
            await result.consume()
        vector = (await provider.embed(["pump pressure inspection"]))[0]
        old = MemoryRecord(
            id="old",
            content="Pump pressure inspected monthly",
            category="career",
            state="Pump needs inspection",
            action="Inspect pressure",
            machine="P1",
            keywords=["pump", "pressure"],
            source="synthetic:test",
            embedding=vector,
            embedding_model="demo:hash-v1",
        )
        await store.upsert(scope, old)
        assert (await store.upsert(scope, old)).id == "old"
        new = MemoryRecord(
            id="new",
            content="Pump pressure inspected annually",
            category="career",
            state="Pump needs inspection",
            action="Inspect pressure annually",
            machine="P1",
            keywords=["pump", "pressure"],
            source="synthetic:test",
            supersedes="old",
            embedding=vector,
            embedding_model="demo:hash-v1",
        )
        await store.upsert(scope, new)
        assert [r.id for r in await store.list(scope)] == ["new"]
        assert len(await store.list(scope, include_legacy=True)) == 2
        assert (await store.retrieve(scope, "pump pressure", embedding=vector))[0].id == "new"
        assert await store.retrieve(scope + "-other", "pump pressure", embedding=vector) == []
        try:
            await store.retrieve(scope, "pump", embedding=[0.5])
        except EmbeddingMismatch:
            pass
        else:
            raise AssertionError("Mismatched vector dimensions were accepted")
        assert await store.delete_session(scope) == 2
        assert await store.list(scope, include_legacy=True) == []
        print(
            json.dumps(
                {
                    "neo4j": "passed",
                    "cases": [
                        "initialization",
                        "idempotency",
                        "temporal_update",
                        "graph_and_vector_retrieval",
                        "session_isolation",
                        "embedding_mismatch",
                        "scoped_deletion",
                    ],
                }
            )
        )
    finally:
        # This scope is generated by this test and cannot name an existing user session.
        await store.delete_session(scope)
        await store.close()


if __name__ == "__main__":
    asyncio.run(verify())
